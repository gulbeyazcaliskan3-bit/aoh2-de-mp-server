window.currentLang = localStorage.getItem("turgut_lang") || "tr";

window.t = function (key) {
  var dict = window.TURGUT_I18N[window.currentLang] || window.TURGUT_I18N.tr;
  return dict[key] || window.TURGUT_I18N.en[key] || key;
};

window.setLanguage = function (langCode) {
  if (!window.TURGUT_I18N[langCode]) return;
  window.currentLang = langCode;
  localStorage.setItem("turgut_lang", langCode);

  var buttons = document.querySelectorAll("[data-lang-btn]");
  for (var i = 0; buttons.length > i; i++) {
    var b = buttons[i];
    if (b.getAttribute("data-lang-btn") === langCode) {
      b.classList.add("btn-gold");
    } else {
      b.classList.remove("btn-gold");
    }
  }

  var textNodes = document.querySelectorAll("[data-i18n]");
  for (var j = 0; textNodes.length > j; j++) {
    var el = textNodes[j];
    var k = el.getAttribute("data-i18n");
    if (k) el.textContent = window.t(k);
  }

  var phNodes = document.querySelectorAll("[data-i18n-ph]");
  for (var m = 0; phNodes.length > m; m++) {
    var inp = phNodes[m];
    var pk = inp.getAttribute("data-i18n-ph");
    if (pk) inp.setAttribute("placeholder", window.t(pk));
  }

  if (typeof window.renderRoomsTable === "function") window.renderRoomsTable();
  if (typeof window.renderDevicesTable === "function") window.renderDevicesTable();
};
